//! Converts the vendored Geany 2.1.0 data (`third_party/geany`) into Ferny's
//! TOML filetypes and colour schemes (`data/`), using Lexilla's tables for
//! lexer names and style numbers.
//!
//! The output keeps Geany's style semantics as strings (named styles,
//! `fore;back;bold;italic`, `,bold`/`,italic` modifiers, named colours);
//! `ferny-syntax` resolves them at runtime against the chosen scheme.
//! Build commands and other executable settings are **not** imported here
//! (they arrive with workspace trust in H2.4).

use std::collections::{BTreeMap, HashMap};
use std::fs;
use std::path::{Path, PathBuf};

use regex::Regex;
use serde::Serialize;

/// Banner written at the top of every generated file.
pub const BANNER: &str = "# Generated by tools/geany-import from Geany 2.1.0 (third_party/geany).\n\
# Do not edit: change the converter or the vendored data and regenerate.\n\n";

/// `[settings]` keys kept (no commands, no paths).
const SETTINGS_KEPT: &[&str] = &[
    "extension",
    "mime_type",
    "comment_single",
    "comment_open",
    "comment_close",
    "comment_use_indent",
    "wordchars",
];
/// `[indentation]` keys kept.
const INDENTATION_KEPT: &[&str] = &["width", "type"];

type Result<T> = std::result::Result<T, String>;

// --- GKeyFile subset ------------------------------------------------------------

/// A group of a key file: optional base filetype (`[styling=C]`) and its
/// entries in file order.
#[derive(Debug, Default, Clone)]
struct Group {
    base: Option<String>,
    entries: Vec<(String, String)>,
}

#[derive(Debug, Default, Clone)]
struct KeyFile {
    groups: Vec<(String, Group)>,
}

impl KeyFile {
    fn parse(text: &str) -> Self {
        let mut file = KeyFile::default();
        for raw in text.lines() {
            let line = raw.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if let Some(header) = line.strip_prefix('[').and_then(|l| l.strip_suffix(']')) {
                let (name, base) = match header.split_once('=') {
                    Some((name, base)) => (name.trim(), Some(base.trim().to_owned())),
                    None => (header.trim(), None),
                };
                file.groups.push((
                    name.to_owned(),
                    Group {
                        base,
                        entries: Vec::new(),
                    },
                ));
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };
            let key = key.trim();
            // Localised keys (name[de]=...) are not imported.
            if key.contains('[') {
                continue;
            }
            if let Some((_, group)) = file.groups.last_mut() {
                group.entries.push((key.to_owned(), unescape(value.trim())));
            }
        }
        file
    }

    fn group(&self, name: &str) -> Option<&Group> {
        self.groups.iter().find(|(n, _)| n == name).map(|(_, g)| g)
    }
}

fn unescape(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    let mut chars = value.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next() {
            Some('s') => out.push(' '),
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some('\\') => out.push('\\'),
            Some(other) => {
                out.push('\\');
                out.push(other);
            }
            None => out.push('\\'),
        }
    }
    out
}

// --- Geany and Lexilla tables ------------------------------------------------------

#[derive(Debug, Clone)]
struct StyleMap {
    style: String,
    key: String,
    fill_eol: bool,
}

#[derive(Debug, Default)]
struct Mappings {
    lexer: HashMap<String, String>,
    styles: HashMap<String, Vec<StyleMap>>,
    keywords: HashMap<String, Vec<(u32, String)>>,
    properties: HashMap<String, Vec<(String, String)>>,
    aliases: HashMap<String, String>,
}

impl Mappings {
    fn parse(text: &str) -> Result<Self> {
        let define =
            Regex::new(r"^#define\s+highlighting_(lexer|styles|keywords|properties)_(\w+)\s+(\w+)")
                .map_err(|e| e.to_string())?;
        let table =
            Regex::new(r"^static const HL(Style|Keyword|Property) highlighting_\w+?_(\w+)\[\]")
                .map_err(|e| e.to_string())?;
        let style = Regex::new(r#"\{\s*(\w+)\s*,\s*"([^"]+)"\s*,\s*(TRUE|FALSE)\s*\}"#)
            .map_err(|e| e.to_string())?;
        let keyword = Regex::new(r#"\{\s*(\d+)\s*,\s*"([^"]+)"\s*,\s*(TRUE|FALSE)\s*\}"#)
            .map_err(|e| e.to_string())?;
        let property =
            Regex::new(r#"\{\s*"([^"]+)"\s*,\s*"([^"]*)"\s*\}"#).map_err(|e| e.to_string())?;

        let mut maps = Mappings::default();
        let mut current: Option<(String, String)> = None;
        for line in text.lines() {
            let line = line.trim();
            if let Some(caps) = define.captures(line) {
                let (kind, lang, value) = (&caps[1], &caps[2], &caps[3]);
                match kind {
                    "lexer" => {
                        maps.lexer.insert(lang.to_owned(), value.to_owned());
                    }
                    _ if value.starts_with("EMPTY_") => {}
                    _ => {
                        let target = value
                            .rsplit_once('_')
                            .map(|(_, l)| l.to_owned())
                            .ok_or_else(|| format!("bad alias {line}"))?;
                        // Alias target LANG is everything after "highlighting_<kind>_".
                        let prefix = format!("highlighting_{kind}_");
                        let target = value.strip_prefix(&prefix).map_or(target, str::to_owned);
                        maps.aliases.insert(format!("{kind}:{lang}"), target);
                    }
                }
                continue;
            }
            if let Some(caps) = table.captures(line) {
                let kind = match &caps[1] {
                    "Style" => "styles",
                    "Keyword" => "keywords",
                    _ => "properties",
                };
                // LANG is the suffix after highlighting_<kind>_.
                let lang = line
                    .split(&format!("highlighting_{kind}_"))
                    .nth(1)
                    .and_then(|rest| rest.split('[').next())
                    .ok_or_else(|| format!("bad table {line}"))?;
                current = Some((kind.to_owned(), lang.to_owned()));
                continue;
            }
            if line.starts_with("};") {
                current = None;
                continue;
            }
            let Some((kind, lang)) = &current else {
                continue;
            };
            match kind.as_str() {
                "styles" => {
                    if let Some(c) = style.captures(line) {
                        maps.styles.entry(lang.clone()).or_default().push(StyleMap {
                            style: c[1].to_owned(),
                            key: c[2].to_owned(),
                            fill_eol: &c[3] == "TRUE",
                        });
                    }
                }
                "keywords" => {
                    if let Some(c) = keyword.captures(line) {
                        let id = c[1].parse().map_err(|_| format!("bad keyword id {line}"))?;
                        maps.keywords
                            .entry(lang.clone())
                            .or_default()
                            .push((id, c[2].to_owned()));
                    }
                }
                _ => {
                    if let Some(c) = property.captures(line) {
                        maps.properties
                            .entry(lang.clone())
                            .or_default()
                            .push((c[1].to_owned(), c[2].to_owned()));
                    }
                }
            }
        }
        Ok(maps)
    }

    fn resolve<'a, T>(
        &'a self,
        kind: &str,
        lang: &str,
        table: &'a HashMap<String, T>,
    ) -> Option<&'a T> {
        let mut lang = lang.to_owned();
        for _ in 0..8 {
            if let Some(found) = table.get(&lang) {
                return Some(found);
            }
            lang = self.aliases.get(&format!("{kind}:{lang}"))?.clone();
        }
        None
    }
}

/// `#define NAME number` from SciLexer.h.
fn sci_constants(text: &str) -> HashMap<String, u32> {
    text.lines()
        .filter_map(|line| {
            let mut parts = line.split_whitespace();
            (parts.next()? == "#define").then_some(())?;
            let name = parts.next()?;
            let value = parts.next()?.parse().ok()?;
            Some((name.to_owned(), value))
        })
        .collect()
}

/// SCLEX_* constant → Lexilla lexer name, from the lexer modules.
fn lexer_names(lexers_dir: &Path) -> Result<HashMap<String, String>> {
    let module = Regex::new(r#"LexerModule\s+lm\w+\s*\(\s*(SCLEX_\w+)\s*,[^,]+,\s*"([^"]+)""#)
        .map_err(|e| e.to_string())?;
    let mut names = HashMap::new();
    let mut entries: Vec<PathBuf> = fs::read_dir(lexers_dir)
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .collect();
    entries.sort();
    for path in entries {
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        for caps in module.captures_iter(&text) {
            names.insert(caps[1].to_owned(), caps[2].to_owned());
        }
    }
    Ok(names)
}

// --- Output ---------------------------------------------------------------------

#[derive(Serialize)]
struct FiletypeOut {
    id: String,
    name: String,
    lexer: String,
    extensions: Vec<String>,
    interpreters: Vec<String>,
    settings: BTreeMap<String, String>,
    indentation: BTreeMap<String, String>,
    properties: BTreeMap<String, String>,
    keywords: Vec<KeywordOut>,
    styles: Vec<StyleOut>,
    /// Geany's own build commands (H2.4): compile, build, lint, execute,
    /// as Geany writes them (split into arguments by ferny-build).
    #[serde(skip_serializing_if = "BTreeMap::is_empty")]
    build: BTreeMap<String, String>,
}

#[derive(Serialize)]
struct KeywordOut {
    set: u32,
    key: String,
    words: String,
}

#[derive(Serialize)]
struct StyleOut {
    style: u32,
    key: String,
    value: String,
    fill_eol: bool,
}

#[derive(Serialize)]
struct SchemeOut {
    id: String,
    name: String,
    description: String,
    author: String,
    license: String,
    colors: BTreeMap<String, String>,
    styles: Vec<NamedStyleOut>,
}

#[derive(Serialize)]
struct NamedStyleOut {
    name: String,
    value: String,
}

fn to_id(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

struct Filetype {
    ft_id: Option<String>,
    /// Name of the Geany configuration file (`cpp` for C++), used as id.
    conf: String,
    name: String,
    keyfile: KeyFile,
}

/// Generates every output file: path relative to the repository → text.
pub fn generate(root: &Path) -> Result<BTreeMap<PathBuf, String>> {
    let geany = root.join("third_party/geany");
    let read = |p: PathBuf| fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display()));

    let sci = sci_constants(&read(root.join("third_party/lexilla/include/SciLexer.h"))?);
    let lexers = lexer_names(&root.join("third_party/lexilla/lexers"))?;
    let maps = Mappings::parse(&read(geany.join("src/highlightingmappings.h"))?)?;
    let filetypes_c = read(geany.join("src/filetypes.c"))?;

    // Built-in filetypes: FT_INIT( ID, PARSER, "Name", title );
    let ft_init =
        Regex::new(r#"FT_INIT\(\s*(\w+)\s*,\s*\w+\s*,\s*"([^"]+)""#).map_err(|e| e.to_string())?;
    let conf_special =
        Regex::new(r#"case GEANY_FILETYPES_(\w+):\s*result = g_strdup\("([^"]+)"\)"#)
            .map_err(|e| e.to_string())?;
    let shebang =
        Regex::new(r#"\{\s*"([^"]+)",\s*GEANY_FILETYPES_(\w+)\s*\}"#).map_err(|e| e.to_string())?;
    let specials: HashMap<String, String> = conf_special
        .captures_iter(&filetypes_c)
        .map(|c| (c[1].to_owned(), c[2].to_owned()))
        .collect();
    let mut interpreters: HashMap<String, Vec<String>> = HashMap::new();
    if let Some(start) = filetypes_c.find("intepreter_map[]") {
        let block = &filetypes_c[start..start + filetypes_c[start..].find("};").unwrap_or(0)];
        for c in shebang.captures_iter(block) {
            interpreters
                .entry(c[2].to_owned())
                .or_default()
                .push(c[1].to_owned());
        }
    }

    let filedefs = geany.join("data/filedefs");
    let mut filetypes: Vec<Filetype> = Vec::new();
    let mut builtin_files: Vec<PathBuf> = Vec::new();
    for caps in ft_init.captures_iter(&filetypes_c) {
        let (ft_id, name) = (caps[1].to_owned(), caps[2].to_owned());
        if ft_id == "NONE" {
            continue;
        }
        let conf = specials
            .get(&ft_id)
            .cloned()
            .unwrap_or_else(|| name.to_lowercase());
        let mut path = filedefs.join(format!("filetypes.{conf}"));
        if !path.exists() {
            // Meson template (placeholders only in build commands, not imported).
            path = filedefs.join(format!("filetypes.{conf}.in"));
        }
        builtin_files.push(path.clone());
        let keyfile = if path.exists() {
            KeyFile::parse(&read(path)?)
        } else {
            KeyFile::default()
        };
        filetypes.push(Filetype {
            ft_id: Some(ft_id),
            name,
            conf,
            keyfile,
        });
    }
    let mut customs: Vec<PathBuf> = fs::read_dir(&filedefs)
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e == "conf") && !builtin_files.contains(p))
        .collect();
    customs.sort();
    for path in customs {
        let name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .and_then(|s| s.strip_prefix("filetypes."))
            .ok_or_else(|| format!("unexpected file {}", path.display()))?
            .to_owned();
        filetypes.push(Filetype {
            ft_id: None,
            conf: name.clone(),
            name,
            keyfile: KeyFile::parse(&read(path)?),
        });
    }

    let extensions_conf = KeyFile::parse(&read(geany.join("data/filetype_extensions.conf"))?);
    let by_name: HashMap<String, usize> = filetypes
        .iter()
        .enumerate()
        .map(|(i, f)| (f.name.clone(), i))
        .collect();

    // A group with inheritance (`[styling=C]`) resolved: base entries, then own.
    let resolve_group = |index: usize, group: &str| -> Vec<(String, String)> {
        let mut chain = Vec::new();
        let mut current = Some(index);
        for _ in 0..8 {
            let Some(i) = current else { break };
            let Some(g) = filetypes[i].keyfile.group(group) else {
                break;
            };
            chain.push(g.entries.clone());
            current = g.base.as_ref().and_then(|b| by_name.get(b).copied());
        }
        let mut merged: Vec<(String, String)> = Vec::new();
        for entries in chain.into_iter().rev() {
            for (key, value) in entries {
                merged.retain(|(k, _)| *k != key);
                merged.push((key, value));
            }
        }
        merged
    };
    let lookup = |entries: &[(String, String)], key: &str| {
        entries
            .iter()
            .find(|(k, _)| k == key)
            .map(|(_, v)| v.clone())
    };

    let mut out = BTreeMap::new();
    for (index, ft) in filetypes.iter().enumerate() {
        let settings = resolve_group(index, "settings");
        let lang = match lookup(&settings, "lexer_filetype") {
            Some(base) => by_name.get(&base).and_then(|&i| filetypes[i].ft_id.clone()),
            None => ft.ft_id.clone(),
        };
        let sclex = lang.as_ref().and_then(|l| {
            // `highlighting_lexer_X` may name another LANG's lexer.
            let mut value = maps.lexer.get(l)?;
            for _ in 0..8 {
                match value.strip_prefix("highlighting_lexer_") {
                    Some(other) => value = maps.lexer.get(other)?,
                    None => break,
                }
            }
            Some(value)
        });
        let lexer = match sclex {
            Some(sclex) => lexers
                .get(sclex)
                .cloned()
                .ok_or_else(|| format!("{}: no Lexilla lexer for {sclex}", ft.name))?,
            None => String::new(),
        };

        let styling = resolve_group(index, "styling");
        let mut styles = Vec::new();
        if let Some(map) = lang
            .as_ref()
            .and_then(|l| maps.resolve("styles", l, &maps.styles))
        {
            for entry in map {
                let style = match entry.style.parse::<u32>() {
                    Ok(n) => n,
                    Err(_) => *sci
                        .get(&entry.style)
                        .ok_or_else(|| format!("{}: unknown style {}", ft.name, entry.style))?,
                };
                styles.push(StyleOut {
                    style,
                    key: entry.key.clone(),
                    value: lookup(&styling, &entry.key).unwrap_or_default(),
                    fill_eol: entry.fill_eol,
                });
            }
        }

        let keyword_group = resolve_group(index, "keywords");
        let mut keywords = Vec::new();
        if let Some(map) = lang
            .as_ref()
            .and_then(|l| maps.resolve("keywords", l, &maps.keywords))
        {
            for (set, key) in map {
                keywords.push(KeywordOut {
                    set: *set,
                    key: key.clone(),
                    words: lookup(&keyword_group, key).unwrap_or_default(),
                });
            }
        }

        let mut properties = BTreeMap::new();
        if let Some(map) = lang
            .as_ref()
            .and_then(|l| maps.resolve("properties", l, &maps.properties))
        {
            for (key, value) in map {
                properties.insert(key.clone(), value.clone());
            }
        }
        for (key, value) in resolve_group(index, "lexer_properties") {
            properties.insert(key, value);
        }

        let kept = |entries: Vec<(String, String)>, allowed: &[&str]| -> BTreeMap<String, String> {
            entries
                .into_iter()
                .filter(|(k, _)| allowed.contains(&k.as_str()))
                .collect()
        };
        let extensions = extensions_conf
            .group("Extensions")
            .and_then(|g| lookup(&g.entries, &ft.name))
            .map(|v| {
                v.split(';')
                    .filter(|s| !s.is_empty())
                    .map(str::to_owned)
                    .collect()
            })
            .unwrap_or_default();

        let file = FiletypeOut {
            id: to_id(&ft.conf),
            name: ft.name.clone(),
            lexer,
            extensions,
            interpreters: ft
                .ft_id
                .as_ref()
                .and_then(|id| interpreters.get(id).cloned())
                .unwrap_or_default(),
            settings: kept(settings, SETTINGS_KEPT),
            indentation: kept(resolve_group(index, "indentation"), INDENTATION_KEPT),
            properties,
            keywords,
            styles,
            build: resolve_group(index, "build-menu")
                .into_iter()
                .filter_map(|(key, value)| {
                    let name = match key.as_str() {
                        "FT_00_CM" => "compile",
                        "FT_01_CM" => "build",
                        "FT_02_CM" => "lint",
                        "EX_00_CM" => "execute",
                        _ => return None,
                    };
                    // Geany's build system substitutes @PYTHON_COMMAND@
                    // (python3 on Unix-like systems, its meson default).
                    let value = value.replace("@PYTHON_COMMAND@", "python3");
                    (!value.trim().is_empty()).then(|| (name.to_owned(), value))
                })
                .collect(),
        };
        let text = toml::to_string(&file).map_err(|e| e.to_string())?;
        out.insert(
            PathBuf::from(format!("data/filetypes/{}.toml", file.id)),
            format!("{BANNER}{text}"),
        );
    }

    // Colour schemes: the built-in default (filetypes.common) plus Geany's.
    let common = KeyFile::parse(&read(filedefs.join("filetypes.common"))?);
    let mut schemes = vec![(
        "default".to_owned(),
        common,
        "GPL-2.0-or-later".to_owned(),
        String::new(),
    )];
    let mut scheme_files: Vec<PathBuf> = fs::read_dir(geany.join("data/colorschemes"))
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e == "conf"))
        .collect();
    scheme_files.sort();
    for path in scheme_files {
        let text = read(path.clone())?;
        let id = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_default()
            .to_owned();
        schemes.push((
            to_id(&id),
            KeyFile::parse(&text),
            scheme_license(&text),
            text,
        ));
    }
    for (id, keyfile, license, _) in schemes {
        let info = keyfile
            .group("theme_info")
            .map(|g| g.entries.clone())
            .unwrap_or_default();
        let name = lookup(&info, "name").unwrap_or_else(|| "Default".to_owned());
        let scheme = SchemeOut {
            id: id.clone(),
            name,
            description: lookup(&info, "description").unwrap_or_default(),
            author: lookup(&info, "author").unwrap_or_default(),
            license,
            colors: keyfile
                .group("named_colors")
                .map(|g| g.entries.iter().cloned().collect())
                .unwrap_or_default(),
            styles: keyfile
                .group("named_styles")
                .map(|g| {
                    g.entries
                        .iter()
                        .map(|(name, value)| NamedStyleOut {
                            name: name.clone(),
                            value: value.clone(),
                        })
                        .collect()
                })
                .unwrap_or_default(),
        };
        let text = toml::to_string(&scheme).map_err(|e| e.to_string())?;
        out.insert(
            PathBuf::from(format!("data/colorschemes/{id}.toml")),
            format!("{BANNER}{text}"),
        );
    }

    // Templates and snippets (H2.5b): Geany's formats, copied verbatim
    // (their text is what users see and edit).
    out.insert(
        PathBuf::from("data/snippets.conf"),
        read(geany.join("data/snippets.conf"))?,
    );
    let templates = geany.join("data/templates");
    for dir in ["", "files"] {
        let mut names: Vec<PathBuf> = fs::read_dir(templates.join(dir))
            .map_err(|e| e.to_string())?
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.is_file())
            .collect();
        names.sort();
        for path in names {
            let name = path.file_name().map(PathBuf::from).unwrap_or_default();
            out.insert(
                PathBuf::from("data/templates").join(dir).join(name),
                read(path)?,
            );
        }
    }
    Ok(out)
}

/// The licence stated in a scheme's header comment (SPDX-like).
fn scheme_license(text: &str) -> String {
    // Header comment lines joined into one line, comment markers removed.
    let header: String = text
        .lines()
        .take_while(|l| l.starts_with('#') || l.trim().is_empty())
        .map(|l| l.trim_start_matches(['#', '~']).trim())
        .collect::<Vec<_>>()
        .join(" ");
    if header.contains("Library General Public") || header.contains("Lesser General Public") {
        "LGPL-2.0-or-later".to_owned()
    } else if header.contains("version 2 of the License, or") {
        "GPL-2.0-or-later".to_owned()
    } else if header.contains("GPL version 2, same as geany") {
        "GPL-2.0-or-later (\"GPL version 2, same as Geany\")".to_owned()
    } else if header.contains("General Public License") {
        "GPL-2.0".to_owned()
    } else if header.contains("Permission is hereby granted") {
        "MIT".to_owned()
    } else if header.contains("Redistribution and use") {
        "BSD".to_owned()
    } else if header.to_lowercase().contains("public domain") {
        "public domain".to_owned()
    } else {
        "unknown".to_owned()
    }
}
