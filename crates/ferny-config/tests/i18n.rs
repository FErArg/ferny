//! Translations (H1.6b, threat T7).
//!
//! `ui/src/core_strings.cpp` lists the English strings that come from the
//! core, so `lupdate` can extract them; this test keeps it current. Run
//! with `FERNY_UPDATE_CORE_STRINGS=1` to rewrite it. The Spanish
//! catalogue must be complete and keep every placeholder of its sources.

use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

use ferny_config::settings::{DESCRIPTORS, Kind};
use ferny_core::command;

fn repo_file(relative: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(relative)
}

fn cpp_literal(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

fn core_strings() -> String {
    let mut contexts: BTreeMap<&str, BTreeSet<String>> = BTreeMap::new();
    let registry = command::builtin_registry();
    let commands = contexts.entry("ferny::commands").or_default();
    for c in registry.commands() {
        commands.insert(c.title().to_owned());
    }
    for menu in registry.menus() {
        commands.insert(menu.title().to_owned());
    }
    let kinds = contexts.entry("ferny::symbols").or_default();
    kinds.extend(
        ferny_syntax::symbols::kinds()
            .into_iter()
            .map(str::to_owned),
    );
    let settings = contexts.entry("ferny::settings").or_default();
    for d in DESCRIPTORS {
        settings.insert(d.title.to_owned());
        if let Kind::Choice(choices) = d.kind {
            settings.extend(choices.iter().map(|c| (*c).to_owned()));
        }
    }
    let mut out = String::from(
        "// Generated by crates/ferny-config/tests/i18n.rs; do not edit.\n\
         // English source strings that come from the Rust core (command, menu\n\
         // and setting titles, choice values, symbol kinds), listed so that\n\
         // lupdate extracts them for translation (H1.6b, H2.2).\n\n\
         #include <QtGlobal>\n\n\
         namespace {\n\n\
         [[maybe_unused]] const char *const kCoreStrings[] = {\n",
    );
    for (context, strings) in &contexts {
        for s in strings {
            out.push_str(&format!(
                "    QT_TRANSLATE_NOOP(\"{context}\", {}),\n",
                cpp_literal(s)
            ));
        }
    }
    out.push_str("};\n\n}  // namespace\n");
    out
}

#[test]
fn core_strings_are_current() {
    let path = repo_file("ui/src/core_strings.cpp");
    let expected = core_strings();
    if std::env::var_os("FERNY_UPDATE_CORE_STRINGS").is_some() {
        std::fs::write(&path, &expected).expect("write core_strings.cpp");
    }
    // Windows checkouts (core.autocrlf / text=auto) store CRLF; the generator writes LF.
    let current = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        current == expected,
        "ui/src/core_strings.cpp is out of date: run \
         `FERNY_UPDATE_CORE_STRINGS=1 cargo test -p ferny-config --test i18n`, \
         then the `update_translations` CMake target"
    );
}

/// One `<message>` of a `.ts` file.
struct Message {
    source: String,
    translations: Vec<String>,
    unfinished: bool,
}

fn unescape(text: &str) -> String {
    text.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}

fn between<'a>(text: &'a str, open: &str, close: &str) -> Vec<&'a str> {
    let mut found = Vec::new();
    let mut rest = text;
    while let Some(start) = rest.find(open) {
        let after = &rest[start + open.len()..];
        let Some(end) = after.find(close) else { break };
        found.push(&after[..end]);
        rest = &after[end + close.len()..];
    }
    found
}

fn messages(ts: &str) -> Vec<Message> {
    between(ts, "<message", "</message>")
        .into_iter()
        .map(|body| {
            let source = between(body, "<source>", "</source>")
                .first()
                .map(|s| unescape(s))
                .unwrap_or_default();
            // `<translation>` or `<translation type="…">`.
            let start = body.find("<translation").unwrap_or(body.len());
            let tag_end = body[start..].find('>').map_or(body.len(), |i| start + i);
            let tag = &body[start..tag_end];
            let inner = between(&body[start..], ">", "</translation>")
                .first()
                .copied()
                .unwrap_or("");
            let forms = between(inner, "<numerusform>", "</numerusform>");
            let translations = if forms.is_empty() {
                vec![unescape(inner)]
            } else {
                forms.into_iter().map(unescape).collect()
            };
            Message {
                source,
                translations,
                unfinished: tag.contains("type="),
            }
        })
        .collect()
}

/// Placeholders: `%1`…`%99`, `%L1`, `%n`, `%Ln`.
fn placeholders(text: &str) -> BTreeSet<String> {
    let chars: Vec<char> = text.chars().collect();
    let mut found = BTreeSet::new();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '%' {
            let mut j = i + 1;
            if chars.get(j) == Some(&'L') {
                j += 1;
            }
            let start = j;
            while chars.get(j).is_some_and(char::is_ascii_digit) && j - start < 2 {
                j += 1;
            }
            if j == start && chars.get(j) == Some(&'n') {
                j += 1;
            }
            if j > start {
                found.insert(chars[start..j].iter().collect());
                i = j;
                continue;
            }
        }
        i += 1;
    }
    found
}

fn spanish() -> Vec<Message> {
    let ts = std::fs::read_to_string(repo_file("ui/translations/ferny_es.ts"))
        .expect("read ferny_es.ts");
    messages(&ts)
}

#[test]
fn translations_are_complete() {
    let all = spanish();
    assert!(all.len() > 100, "catalogue looks empty: {}", all.len());
    for m in &all {
        assert!(!m.unfinished, "unfinished or obsolete: {:?}", m.source);
        assert!(
            m.translations.iter().all(|t| !t.trim().is_empty()),
            "empty translation: {:?}",
            m.source
        );
    }
}

#[test]
fn translations_keep_placeholders() {
    for m in spanish() {
        let expected = placeholders(&m.source);
        for t in &m.translations {
            assert_eq!(
                placeholders(t),
                expected,
                "placeholders differ: {:?} -> {:?}",
                m.source,
                t
            );
        }
    }
}

#[test]
fn placeholder_scanner() {
    let set = |v: &[&str]| v.iter().map(|s| (*s).to_owned()).collect::<BTreeSet<_>>();
    assert_eq!(
        placeholders("%1 of %L2, %n item(s), 100%"),
        set(&["1", "2", "n"])
    );
    assert_eq!(placeholders("no placeholders"), set(&[]));
}
